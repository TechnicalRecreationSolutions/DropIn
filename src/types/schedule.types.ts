import type { Database } from "./database.types";

export type Session = Database["public"]["Tables"]["sessions"]["Row"];
export type SessionException =
  Database["public"]["Tables"]["session_exceptions"]["Row"];
export type ScheduleGroup = Database["public"]["Tables"]["schedule_groups"]["Row"];
export type Facility = Database["public"]["Tables"]["facilities"]["Row"];
export type FacilityMap = Database["public"]["Tables"]["facility_maps"]["Row"];
export type SpaceHotspot = Database["public"]["Tables"]["space_hotspots"]["Row"];
export type MapContextElement =
  Database["public"]["Tables"]["map_context_elements"]["Row"];

/** A hotspot joined with its space's display info, as returned to the public floorplan view. */
export type SpaceHotspotWithSpace = SpaceHotspot & {
  spaceName: string;
  spaceCapacity: number | null;
};

/**
 * A concrete, expanded occurrence of a recurring session.
 * Generated by lib/rrule/expand.ts from a Session row + its exceptions.
 */
export type ExpandedSession = {
  /** Unique key for this specific occurrence: `${sessionId}_${date}` */
  key: string;
  sessionId: string;
  orgId: string;

  /**
   * This occurrence's local wall-clock start/end, stored as literal
   * UTC-labelled digits with no real instant meaning (see
   * dropin/docs/RESUME-timezone-removal.md and rrule/README.md). Read with
   * getUTCHours()/getUTCDate()/etc — via `formatSessionTime`/
   * `formatSessionDayFull`/`sessionDateString` (src/lib/utils/dates.ts) for
   * display — never through the runtime-local getters `formatTime`/
   * `formatDayFull`/`new Date().toDateString()` use, which would read a
   * different, wrong wall-clock value on any machine not itself in UTC.
   */
  start: Date;
  end: Date;

  /** Denormalized schedule group info for display without extra fetches */
  scheduleGroupId: string;
  scheduleGroupName: string;
  sportCategory: string;
  activityType: ScheduleGroup["activity_type"];
  costCents: number;
  costNotes: string | null;
  ageGroup: string | null;
  skillLevel: string | null;
  maxParticipants: number | null;

  /** Denormalized facility info */
  facilityId: string;
  facilityName: string;

  /** Denormalized department info — null if the schedule group has no department */
  departmentId: string | null;
  departmentName: string | null;

  /** Structured spaces within the facility this session occupies, if any (e.g. all of Lanes 1-4 for a shared Lap Swim block) */
  spaceIds: string[];
  spaceNames: string[];

  /** Session template this occurrence was placed from, if any (see session_templates) */
  templateId: string | null;
  templateName: string | null;
  templateColor: string | null;

  /** Free-text location note — shown alongside the space, e.g. entry instructions */
  locationDetail: string | null;

  /**
   * Set when this occurrence was modified by a session_exception.
   * 'cancelled' occurrences are excluded from the output entirely.
   */
  isModified?: boolean;
  modificationNote?: string | null;
};

/** Which visual layout a schedule is rendered as. */
export type ScheduleTemplate = "grid" | "list" | "map" | "floorplan";

/**
 * Parameters for expanding sessions across a date range.
 *
 * This was once strictly week-shaped (`weekStart`/`weekEnd`). Nothing about
 * expansion was ever week-specific — the RRULE is evaluated between two
 * instants — so the range is arbitrary, and the caller decides whether that's
 * a week or a month. `/api/sessions/expand` caps how wide it may be.
 */
export type RangeExpandParams = {
  rangeStart: Date;
  rangeEnd: Date;
  orgId?: string;
  facilityId?: string;
  departmentId?: string;
  scheduleGroupId?: string;
};

/** Grid position for rendering in the weekly schedule grid */
export type GridPosition = {
  /** Column index (0 = Sunday ... 6 = Saturday) */
  dayIndex: number;
  /** Minutes from the grid's start time (e.g. 360 = 6:00 AM if grid starts at midnight) */
  startMinute: number;
  /** Duration in minutes */
  durationMinutes: number;
};
