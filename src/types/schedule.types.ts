/** A hotspot joined with its space's display info, as returned to the public floorplan view. */
export type SpaceHotspotWithSpace = SpaceHotspot & {
  spaceName: string;
  spaceCapacity: number | null;
};

/**
 * The presentation payload shared by the event calendar and the brochure
 * (`session_features`). One record per session, two channels — see the header
 * of migration 028 for why the copy is not duplicated per channel.
 */
export type SessionFeatureContent = {
  /** Overrides the schedule group's name on feature surfaces. Null means "use the schedule group's name". */
  title: string | null;
  /** One line, for a calendar cell. */
  summary: string | null;
  /** Long copy, for the brochure and the detail sheet. */
  description: string | null;
  imageUrl: string | null;
  linkUrl: string | null;
  linkLabel: string | null;
  /** Org-defined label, not a fixed taxonomy. */
  eventCategory: string | null;
  accentColor: string | null;
};

/**
 * What an event is called on a calendar or in a brochure.
 *
 * The fallback chain matters: a featured session usually has no override at
 * all (it's "Family Swim", already named by its schedule group), and only a
 * genuine one-off — "Halloween Howl" — bothers to set a title. Falling back
 * through the template name first keeps a placed template's own label, which
 * is what staff see in the builder.
 */
export function eventDisplayTitle(
  session: Pick<ExpandedSession, "feature" | "templateName" | "scheduleGroupName">
): string {
  return session.feature?.title ?? session.templateName ?? session.scheduleGroupName;
}

/**
 * A concrete, expanded occurrence of a recurring session.
 * Generated by lib/rrule/expand.ts from a Session row + its exceptions.
 */
export type ExpandedSession = {
  /** Unique key for this specific occurrence: `${sessionId}_${date}` */
  key: string;
  sessionId: string;
  orgId: string;

  /** Absolute start datetime for this occurrence */
  start: Date;
  /** Absolute end datetime for this occurrence */
  end: Date;

  /** Denormalized schedule group info for display without extra fetches */
  scheduleGroupId: string;
  scheduleGroupName: string;
  sportCategory: string;
  activityType: ScheduleGroup["activity_type"];
  costCents: number;
  costNotes: string | null;
  ageGroup: string | null;
  skillLevel: string | null;
  maxParticipants: number | null;

  /** Denormalized facility info */
  facilityId: string;
  facilityName: string;

  /** Denormalized department info — null if the schedule group has no department */
  departmentId: string | null;
  departmentName: string | null;

  /** Structured spaces within the facility this session occupies, if any (e.g. all of Lanes 1-4 for a shared Lap Swim block) */
  spaceIds: string[];
  spaceNames: string[];

  /** Session template this occurrence was placed from, if any (see session_templates) */
  templateId: string | null;
  templateName: string | null;
  templateColor: string | null;

  /** Season this session was explicitly assigned to, if any (see seasons / migration 027). */
  seasonId: string | null;

  /** On the event calendar. */
  isEvent: boolean;
  /** A candidate for a season's brochure — candidacy, not membership. */
  inBrochure: boolean;
  /**
   * The copy behind both toggles (session_features). Null when this session has
   * never been featured. Present even when both toggles are off, because
   * un-featuring deliberately keeps the copy — see migration 028.
   */
  feature: SessionFeatureContent | null;

  /** Free-text location note — shown alongside the space, e.g. entry instructions */
  locationDetail: string | null;

  /**
   * Set when this occurrence was modified by a session_exception.
   * 'cancelled' occurrences are excluded from the output entirely.
   */
  isModified?: boolean;
  modificationNote?: string | null;
};

/** Which visual layout a schedule is rendered as. */
export type ScheduleTemplate = "grid" | "list" | "map" | "floorplan" | "events";

/**
 * Parameters for expanding sessions across a date range.
 *
 * This was week-shaped (`weekStart`/`weekEnd`) until the event calendar needed
 * a month. Nothing about expansion was ever week-specific — the RRULE is
 * evaluated between two instants — so the range is now arbitrary, and the
 * caller decides whether that's a week, a month, or a season. `/api/sessions/expand`
 * caps how wide it may be.
 */
export type RangeExpandParams = {
  rangeStart: Date;
  rangeEnd: Date;
  orgId?: string;
  facilityId?: string;
  departmentId?: string;
  scheduleGroupId?: string;
  /**
   * Narrows to sessions explicitly assigned to this season. Orthogonal to the
   * scope filters above — a season spans every facility in the org, so this
   * never satisfies the "at least one scope" requirement on its own.
   */
  seasonId?: string;
  /** Only sessions flagged `is_event` — what the event calendar asks for. */
  eventsOnly?: boolean;
};

/** Grid position for rendering in the weekly schedule grid */
export type GridPosition = {
  /** Column index (0 = Monday ... 6 = Sunday) */
  dayIndex: number;
  /** Minutes from the grid's start time (e.g. 360 = 6:00 AM if grid starts at midnight) */
  startMinute: number;
  /** Duration in minutes */
  durationMinutes: number;
};
